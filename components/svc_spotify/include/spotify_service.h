/*
 * The Spotify service: owns the "spotify" task (ARCHITECTURE.md §4: core 0,
 * prio 5, 8KB, adaptive 1-30s cadence, blocking allowed), the session FSM,
 * the playback-intent queue, and the console control-command queue.
 *
 * Target-only -- this header (and every .c file that includes it) is
 * never linked into a host test. See spotify_service_state.h's top
 * comment for the reason (transitively embeds a net_http_t pointer and a
 * net_time_t pointer, which pull in FreeRTOS) and for what IS host-tested
 * instead: the pure spotify_service_state_t this struct embeds as its
 * `state` field.
 *
 * svc_spotify cannot depend on svc_settings/svc_supervisor directly (no
 * svc->svc edge) -- app_wiring mediates, same as svc_denon: cfg carries
 * resolved config (client_id/redirect_uri already seeded from Kconfig if
 * nothing was stored) taken once at construction.
 *
 * Sync-gating (Phase 4 plan §2): svc_spotify holds a direct net_time_t*
 * (legal svc->net_* dependency, same as net_http_t*) and reads
 * `time->synced` directly before any real network/epoch-sensitive action --
 * the boot dependency graph alone does NOT guarantee SNTP has synced by
 * the time this code runs (verified directly against svc_supervisor.c/
 * net_time.c), so this is a real runtime check, not an assumption.
 *
 * Cross-boundary action-result flags (spotify_service_state.h's
 * token_op_just_ran/result/tokens): core_fsm_dispatch() runs an action
 * BEFORE updating current_state, so an action cannot safely re-dispatch
 * into the FSM itself. Every session_fsm action instead performs its I/O
 * synchronously and stores the result there; spotify_service_session_drive()
 * -- called every iteration of the spotify task's own loop -- notices a
 * set flag and dispatches the real follow-up event from OUTSIDE any
 * action, identical to denon_service_link.c's own discipline.
 */

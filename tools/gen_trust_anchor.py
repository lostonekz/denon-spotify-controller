#!/usr/bin/env python3
"""
Reads an ECDSA P-256 manifest-signing key's PUBLIC half and emits
components/svc_ota/ota_trust_anchor_dev.c: a compiled-in ota_trust_anchor_t
table for ota_trust_anchors.h's pure lookup (docs/SECURITY.md §4: "the
firmware holds two trust anchors: current and next"). Phase 2 only has one
dev key, so this emits a one-entry table; a second call with --key-id set
to the rotation key and --out pointed at a second generated file is how a
real "next" anchor would be added later (not needed yet -- ADR-0006's
staged security).

Uses `openssl ec ... -pubout -outform DER` via subprocess rather than a
Python crypto library: no new pip dependency, and openssl is already this
project's tool of choice for the RSA image-signing key (tools/keys/README.md).

The generated identifier name deliberately contains the literal substring
"DEV_TRUST_ANCHOR" and the key_id follows the "dsc-dev-" convention --
tools/check_release.py's scan_for_dev_key() already scans main/ and
components/ file CONTENTS for exactly these two marker strings, so a
production build that accidentally still compiles this file in fails that
gate. This is deliberate, not a marker to avoid: shipping a production
build that would still accept a manifest signed by the dev key defeats the
whole point of a separate release key.

WHY --check ISN'T A GIT-DIFF GATE (unlike ota_manifest_oracle.py --check-c)
The source of truth here -- tools/keys/dev_manifest_signing.pem -- is
gitignored, generated locally per developer (or fresh by CI each run,
tools/keys/README.md's existing rationale for the RSA key applies
identically). There is no committed source to diff the generated file
against. --check instead verifies *local self-consistency*: does the
checked-in ota_trust_anchor_dev.c match what the CURRENT on-disk key would
produce right now. Missing key material is treated as an expected,
not-yet-populated state (same posture as check_release.py's dev-profile
check), not a failure.

Usage:
    python tools/gen_trust_anchor.py                # (re)generate from the dev key
    python tools/gen_trust_anchor.py --check         # local-consistency gate
"""

import argparse
import os
import subprocess
import sys

DEFAULT_KEY_ID = "dsc-dev-2026-07"


def pubkey_der(key_path):
    proc = subprocess.run(
        ["openssl", "ec", "-in", key_path, "-pubout", "-outform", "DER"],
        stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if proc.returncode != 0:
        raise RuntimeError("openssl failed to extract the public key from %s: %s"
                            % (key_path, proc.stderr.decode("utf-8", "replace")))
    return proc.stdout


def generate_c(der_bytes, key_id, src_name):
    hex_bytes = ", ".join("0x%02x" % b for b in der_bytes)
    lines = [
        "/* GENERATED by tools/gen_trust_anchor.py from %s -- DO NOT EDIT." % src_name,
        " * Regenerate: python tools/gen_trust_anchor.py",
        " *",
        " * The dev key protects nothing (tools/keys/README.md) -- this file",
        " * embeds only its PUBLIC half, safe to commit. A production build",
        " * must not compile this in; tools/check_release.py's prod profile",
        " * fails if it does (scan_for_dev_key() matches \"DEV_TRUST_ANCHOR\"",
        " * and \"dsc-dev-\" in this file's own content). */",
        "#include \"ota_trust_anchor_dev.h\"",
        "",
        "static const uint8_t DSC_DEV_TRUST_ANCHOR_PUBKEY_DER[] = {",
        "    %s," % hex_bytes,
        "};",
        "",
        "const ota_trust_anchor_t DSC_DEV_TRUST_ANCHORS[] = {",
        "    {",
        '        .key_id          = "%s",' % key_id,
        "        .pubkey_der      = DSC_DEV_TRUST_ANCHOR_PUBKEY_DER,",
        "        .pubkey_der_len = sizeof(DSC_DEV_TRUST_ANCHOR_PUBKEY_DER),",
        "    },",
        "};",
        "",
        "const size_t DSC_DEV_TRUST_ANCHOR_COUNT = "
        "sizeof(DSC_DEV_TRUST_ANCHORS) / sizeof(DSC_DEV_TRUST_ANCHORS[0]);",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--key", default=None, help="path to the ECDSA P-256 private key PEM")
    ap.add_argument("--key-id", default=DEFAULT_KEY_ID)
    ap.add_argument("--out", default=None, help="output .c path")
    ap.add_argument("--check", action="store_true",
                     help="local-consistency gate -- see this script's own docstring")
    args = ap.parse_args()

    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(here)
    key_path = args.key or os.path.join(root, "tools", "keys", "dev_manifest_signing.pem")
    out_path = args.out or os.path.join(root, "components", "svc_ota", "ota_trust_anchor_dev.c")

    if not os.path.exists(key_path):
        print("NOTE: no dev manifest-signing key found yet at %s "
              "(expected once tools/keys/ is populated)" % key_path)
        return 0

    try:
        der = pubkey_der(key_path)
    except RuntimeError as e:
        print("FAILED: %s" % e)
        return 1

    fresh = generate_c(der, args.key_id, os.path.basename(key_path))

    if args.check:
        if not os.path.exists(out_path):
            print("MISSING generated file: %s" % out_path)
            print("  run: python tools/gen_trust_anchor.py")
            return 1
        with open(out_path, encoding="utf-8") as fh:
            on_disk = fh.read()
        if on_disk.replace("\r\n", "\n") != fresh.replace("\r\n", "\n"):
            print("STALE: %s does not match the current key at %s" % (out_path, key_path))
            print("  run: python tools/gen_trust_anchor.py")
            return 1
        print("ota_trust_anchor_dev.c matches the current dev key")
        return 0

    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(fresh)
    print("wrote %s (key_id=%s, %d-byte DER pubkey)" % (out_path, args.key_id, len(der)))
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""
Independent Python implementation of the OTA manifest canonical-bytes
encoding (the fixed-order binary layout that gets ECDSA-signed, docs/
SECURITY.md §3), plus a validator/generator for
test/host/ota_manifest_vectors.csv.

WHY THIS EXISTS
The C encoder (components/svc_ota/ota_manifest_parse.c) and this oracle are
written from the same spec (components/svc_ota/include/ota_manifest.h's
doc comment), not from each other. A hand-mirrored binary encoding in two
languages is exactly the kind of thing that silently drifts apart -- this
is the same reasoning tools/denon_mv_oracle.py already applies to the
Denon MV codec, applied to the manifest signing format instead.

Usage:
    python tools/ota_manifest_oracle.py            # validate the vector table
    python tools/ota_manifest_oracle.py --gen-c    # (re)generate the C include
    python tools/ota_manifest_oracle.py --check-c  # CI gate: fail if stale
"""

import argparse
import csv
import os
import struct
import sys


def _str8(s):
    b = s.encode("utf-8")
    if len(b) > 0xFF:
        raise ValueError("string too long for a 1-byte length prefix: %r" % s)
    return bytes([len(b)]) + b


def _str16(s):
    b = s.encode("utf-8")
    if len(b) > 0xFFFF:
        raise ValueError("string too long for a 2-byte length prefix: %r" % s)
    return struct.pack(">H", len(b)) + b


def canonical_bytes(version, build, security_version, url, sha256_hex,
                     size, key_id, min_prev_build, mandatory, notes):
    """Mirrors ota_manifest_canonical_bytes() in
    components/svc_ota/ota_manifest_parse.c field-for-field. Excludes the
    signature itself, same as the C side."""
    sha256 = bytes.fromhex(sha256_hex)
    if len(sha256) != 32:
        raise ValueError("sha256_hex must decode to 32 bytes (64 hex chars): %r" % sha256_hex)

    out = bytearray()
    out += _str8(version)
    out += struct.pack(">I", build)
    out += struct.pack(">I", security_version)
    out += _str16(url)
    out += sha256
    out += struct.pack(">I", size)
    out += _str8(key_id)
    out += struct.pack(">I", min_prev_build)
    out += bytes([1 if mandatory else 0])
    out += _str16(notes)
    return bytes(out)


def load_vectors(path):
    rows = []
    with open(path, newline="", encoding="utf-8") as fh:
        for raw in fh:
            raw = raw.strip()
            if not raw or raw.startswith("#") or raw.startswith("name,"):
                continue
            parts = next(csv.reader([raw]))
            if len(parts) < 12:
                continue
            rows.append({
                "name":                 parts[0].strip(),
                "version":              parts[1],
                "build":                int(parts[2]),
                "security_version":     int(parts[3]),
                "url":                  parts[4],
                "sha256_hex":           parts[5].strip(),
                "size":                 int(parts[6]),
                "key_id":               parts[7],
                "min_prev_build":       int(parts[8]),
                "mandatory":            parts[9].strip().lower() == "true",
                "notes":                parts[10],
                "expected_canonical_hex": parts[11].strip(),
            })
    return rows


def validate(path):
    rows = load_vectors(path)
    failures = []

    for i, r in enumerate(rows, 1):
        try:
            got = canonical_bytes(
                r["version"], r["build"], r["security_version"], r["url"],
                r["sha256_hex"], r["size"], r["key_id"], r["min_prev_build"],
                r["mandatory"], r["notes"])
        except ValueError as e:
            failures.append("%s:%d %s: %s" % (path, i, r["name"], e))
            continue

        got_hex = got.hex()
        if got_hex != r["expected_canonical_hex"]:
            failures.append("%s:%d %s: canonical_bytes = %s, table says %s"
                            % (path, i, r["name"], got_hex, r["expected_canonical_hex"]))

    return rows, failures


def c_escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def generate_c(rows, out_path, src_name):
    """Emit the vector table as a C include. Single source of truth stays the
    CSV; CI regenerates and diffs so the two cannot drift."""
    lines = [
        "/* GENERATED by tools/ota_manifest_oracle.py from %s -- DO NOT EDIT." % src_name,
        " * Regenerate: python tools/ota_manifest_oracle.py --gen-c",
        " * CI fails if this file differs from a fresh generation. */",
        "",
        "typedef struct {",
        "    const char *name;",
        "    const char *version;",
        "    uint32_t    build;",
        "    uint32_t    security_version;",
        "    const char *url;",
        "    const char *sha256_hex;      /* 64 hex chars */",
        "    uint32_t    size;",
        "    const char *key_id;",
        "    uint32_t    min_prev_build;",
        "    bool        mandatory;",
        "    const char *notes;",
        "    const char *expected_canonical_hex;",
        "} ota_manifest_vector_t;",
        "",
        "static const ota_manifest_vector_t OTA_MANIFEST_VECTORS[] = {",
    ]

    for r in rows:
        lines.append(
            '    { "%s", "%s", %d, %d, "%s", "%s", %d, "%s", %d, %s, "%s", "%s" },'
            % (c_escape(r["name"]), c_escape(r["version"]), r["build"],
               r["security_version"], c_escape(r["url"]), r["sha256_hex"],
               r["size"], c_escape(r["key_id"]), r["min_prev_build"],
               "true" if r["mandatory"] else "false", c_escape(r["notes"]),
               r["expected_canonical_hex"]))

    lines.append("};")
    lines.append("#define OTA_MANIFEST_VECTORS_COUNT %d" % len(rows))
    lines.append("")

    text = "\n".join(lines)
    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    return text


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--vectors", default=None)
    ap.add_argument("--gen-c", action="store_true",
                    help="regenerate the C vector include")
    ap.add_argument("--check-c", action="store_true",
                    help="fail if the C include is stale (CI gate)")
    args = ap.parse_args()

    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(here)
    path = args.vectors or os.path.join(root, "test", "host", "ota_manifest_vectors.csv")

    if not os.path.exists(path):
        print("MISSING vector table: %s" % path)
        return 1

    rows, failures = validate(path)
    inc_path = os.path.join(root, "test", "host", "ota_manifest_vectors.inc")

    if args.gen_c:
        if failures:
            print("Refusing to generate from a table that fails validation:")
            for f in failures:
                print("  FAIL %s" % f)
            return 1
        generate_c(rows, inc_path, "ota_manifest_vectors.csv")
        print("wrote %s (%d vectors)" % (inc_path, len(rows)))
        return 0

    if args.check_c:
        if not os.path.exists(inc_path):
            print("MISSING generated include: %s" % inc_path)
            print("  run: python tools/ota_manifest_oracle.py --gen-c")
            return 1
        with open(inc_path, encoding="utf-8") as fh:
            on_disk = fh.read()
        tmp = inc_path + ".check"
        fresh = generate_c(rows, tmp, "ota_manifest_vectors.csv")
        os.remove(tmp)
        if on_disk.replace("\r\n", "\n") != fresh.replace("\r\n", "\n"):
            print("STALE: %s does not match ota_manifest_vectors.csv" % inc_path)
            print("  run: python tools/ota_manifest_oracle.py --gen-c")
            return 1
        print("ota_manifest vectors: C include is in sync with the CSV")
        return 0

    print("ota_manifest_oracle: %d vector(s)" % len(rows))
    for f in failures:
        print("  FAIL %s" % f)
    if failures:
        print("FAILED: %d vector mismatch(es)" % len(failures))
        return 1
    print("OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""
Generates main/fw_version_generated.h from fw_version.json -- the single
source of truth for this build's own version/build/security_version
(docs/SECURITY.md §3: "the device stores the highest [security_version] it
has ever run"; this is what it's currently running).

WHY A GENERATED HEADER, NOT A HAND-WRITTEN CONSTANT
Bumping the version in fw_version.json (what tools/gen_manifest.py reads to
build a release manifest) and in the firmware's own compiled-in value are
the classic two places to forget to keep in sync. One generated header
read by both eliminates the drift entirely.

WHY main/, NOT A COMPONENT
svc_ota needs this build's compiled_build/compiled_security_version, but
only as plain values injected into svc_ota_cfg_t at construction --
main/app_wiring.c (which already depends on everything) reads this header
and passes the values in. svc_ota itself never includes it: components
must not depend on main (arch_rules.json's layering), so the generated
header stays out of any component's include path entirely.

Usage:
    python tools/gen_fw_version_header.py            # (re)generate the header
    python tools/gen_fw_version_header.py --check     # CI gate: fail if stale
"""

import argparse
import json
import os
import re
import sys


def load_version(path):
    with open(path, encoding="utf-8") as fh:
        data = json.load(fh)

    for key in ("version", "build", "security_version"):
        if key not in data:
            raise ValueError("%s missing required key %r" % (path, key))

    version = data["version"]
    build = data["build"]
    security_version = data["security_version"]

    if not re.match(r"^[0-9A-Za-z.\-]+$", version):
        raise ValueError("version has unexpected characters: %r" % version)
    if not isinstance(build, int) or build < 0:
        raise ValueError("build must be a non-negative integer: %r" % build)
    if not isinstance(security_version, int) or security_version < 0:
        raise ValueError("security_version must be a non-negative integer: %r" % security_version)

    return version, build, security_version


def generate_header(version, build, security_version, src_name):
    lines = [
        "/* GENERATED by tools/gen_fw_version_header.py from %s -- DO NOT EDIT." % src_name,
        " * Regenerate: python tools/gen_fw_version_header.py",
        " * CI fails if this file differs from a fresh generation. */",
        "#ifndef DSC_FW_VERSION_GENERATED_H",
        "#define DSC_FW_VERSION_GENERATED_H",
        "",
        '#define DSC_FW_VERSION "%s"' % version,
        "#define DSC_FW_BUILD %dU" % build,
        "#define DSC_FW_SECURITY_VERSION %dU" % security_version,
        "",
        "#endif /* DSC_FW_VERSION_GENERATED_H */",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                     help="fail if the generated header is stale (CI gate)")
    args = ap.parse_args()

    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(here)
    src_path = os.path.join(root, "fw_version.json")
    out_path = os.path.join(root, "main", "fw_version_generated.h")

    if not os.path.exists(src_path):
        print("MISSING %s" % src_path)
        return 1

    try:
        version, build, security_version = load_version(src_path)
    except ValueError as e:
        print("INVALID fw_version.json: %s" % e)
        return 1

    fresh = generate_header(version, build, security_version, "fw_version.json")

    if args.check:
        if not os.path.exists(out_path):
            print("MISSING generated header: %s" % out_path)
            print("  run: python tools/gen_fw_version_header.py")
            return 1
        with open(out_path, encoding="utf-8") as fh:
            on_disk = fh.read()
        if on_disk.replace("\r\n", "\n") != fresh.replace("\r\n", "\n"):
            print("STALE: %s does not match fw_version.json" % out_path)
            print("  run: python tools/gen_fw_version_header.py")
            return 1
        print("fw_version_generated.h is in sync with fw_version.json")
        return 0

    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(fresh)
    print("wrote %s (version=%s build=%d security_version=%d)" % (out_path, version, build, security_version))
    return 0


if __name__ == "__main__":
    sys.exit(main())
